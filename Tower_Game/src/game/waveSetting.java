package game;

public class waveSetting {
    public int goblins;
    public int knights;
    public int tnts;
    public int healers;

    public waveSetting(int goblins, int knights, int tnts, int healers) {
        this.goblins = goblins;
        this.knights = knights;
        this.tnts = tnts;
        this.healers = healers;
    }
}
